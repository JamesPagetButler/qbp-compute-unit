package mdcu

// POST-HOC DIAGNOSTIC (arch seq 89, "explain the R3-Q2 disagreement"):
// a straight-line, table-free W2 non-CD kernel with the SAME multiply structure
// as W2NonCD (21 minors = 42 multiplies, then 7 dot multiplies = 49). It exists
// only to test whether the R3-Q2 W2 host-ns gap is table-lookup overhead in
// W2NonCD. It changes no R3 verdict. W2NonCD / W2CD themselves are untouched.
//
// The kernel in r3q2_w2unrolled.go is GENERATED from crossTab/minorIdx by
// TestGenW2Unrolled (run with MDCU_GEN_W2=1), so no sign is typed by hand.
// TestW2UnrolledIsGenerated pins the committed file to the generator output.

import (
	"fmt"
	"math"
	"os"
	"strings"
	"testing"
)

// genW2UnrolledSource renders the unrolled kernel from the frozen tables.
func genW2UnrolledSource() string {
	var sb strings.Builder
	sb.WriteString("// Code generated by TestGenW2Unrolled (MDCU_GEN_W2=1 go test ./mdcu/ -run TestGenW2Unrolled); DO NOT EDIT.\n")
	sb.WriteString("// POST-HOC DIAGNOSTIC kernel, see r3q2_w2unrolled_test.go. Not part of any frozen verdict.\n\n")
	sb.WriteString("package mdcu\n\n")
	sb.WriteString("// W2NonCDUnrolled computes a·(b×c) like W2NonCD (21 minors of (a,b), then\n")
	sb.WriteString("// a 7-term dot with c) but as straight-line code with no table lookups.\n")
	sb.WriteString("func W2NonCDUnrolled(in *V3In, t *Tape) float64 {\n")
	sb.WriteString("\ta, b, c := &in.A, &in.B, &in.C\n")
	for j := 1; j < 8; j++ {
		for k := j + 1; k < 8; k++ {
			fmt.Fprintf(&sb, "\tm%d := a[%d]*b[%d] - a[%d]*b[%d]\n", minorIdx[j][k], j, k, k, j)
		}
	}
	sb.WriteString("\tn := t.add(42)\n")
	sb.WriteString("\ts := 0.0\n")
	for i := 1; i < 8; i++ {
		var expr strings.Builder
		for p, e := range crossTab[i-1] {
			name := fmt.Sprintf("m%d", minorIdx[e[0]][e[1]])
			switch {
			case p == 0 && e[2] > 0:
				expr.WriteString(name)
			case p == 0:
				expr.WriteString("-" + name)
			case e[2] > 0:
				expr.WriteString(" + " + name)
			default:
				expr.WriteString(" - " + name)
			}
		}
		fmt.Fprintf(&sb, "\ts += c[%d] * (%s)\n", i, expr.String())
	}
	sb.WriteString("\tt.add(7, n)\n")
	sb.WriteString("\treturn s\n}\n")
	return sb.String()
}

func TestW2UnrolledAgrees(t *testing.T) {
	ins := NewV3Ins(1000, 9830) // out-of-grid, fixed
	worst := 0.0
	for k := range ins {
		u := W2NonCDUnrolled(&ins[k], nil)
		r := W2NonCD(&ins[k], nil)
		cd := W2CD(&ins[k], nil)
		for _, ref := range []float64{r, cd} {
			if d := math.Abs(u-ref) / (1 + math.Abs(ref)); d > worst {
				worst = d
			}
		}
	}
	if worst > 1e-12 {
		t.Fatalf("unrolled W2 disagrees with W2NonCD/W2CD: worst relative error %g", worst)
	}
}

func TestW2UnrolledMultiplyCount(t *testing.T) {
	ins := NewV3Ins(1, 9831)
	var tu, tr Tape
	W2NonCDUnrolled(&ins[0], &tu)
	W2NonCD(&ins[0], &tr)
	if got := tu.TotalMults(); got != 49 {
		t.Fatalf("unrolled W2 multiplies = %d, want 49", got)
	}
	if tu.TotalMults() != tr.TotalMults() {
		t.Fatalf("unrolled %d != W2NonCD %d multiplies", tu.TotalMults(), tr.TotalMults())
	}
}

func TestW2UnrolledIsGenerated(t *testing.T) {
	b, err := os.ReadFile("r3q2_w2unrolled.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(b) != genW2UnrolledSource() {
		t.Fatal("r3q2_w2unrolled.go is not the generator output; regenerate with MDCU_GEN_W2=1 go test ./mdcu/ -run TestGenW2Unrolled")
	}
}

// TestGenW2Unrolled writes the kernel file when MDCU_GEN_W2 is set; otherwise skipped.
func TestGenW2Unrolled(t *testing.T) {
	if os.Getenv("MDCU_GEN_W2") == "" {
		t.Skip("set MDCU_GEN_W2=1 to regenerate r3q2_w2unrolled.go")
	}
	if err := os.WriteFile("r3q2_w2unrolled.go", []byte(genW2UnrolledSource()), 0o644); err != nil {
		t.Fatal(err)
	}
}
